import { readFile, mkdir, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import Ajv from 'ajv';
import standalone from 'ajv/dist/standalone/index.js';

// MV3 forbids runtime code generation. Compile the normative schemas at build
// time, so the worker and preview use the contract without unsafe-eval.
const app = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const ajv = new Ajv({ allErrors: true, strict: true, code: { source: true, esm: true } });
for (const file of ['portable.schema.json', 'api-summary.schema.json']) {
    ajv.addSchema(JSON.parse(await readFile(resolve(app, '../../contracts/theme', file), 'utf8')));
}
let code = standalone(ajv, {
    portable: 'https://moodle-theme-shop.invalid/contracts/theme/portable-v1.schema.json',
    api: 'https://moodle-theme-shop.invalid/contracts/theme/api-summary-v1.schema.json',
});
// Ajv standalone emits CommonJS references for its small Unicode helper even in
// ESM mode. Turn those references into imports for Vite's browser bundling.
code = code.replace(/const (\w+) = require\(("[^"]+")\)\.default;/g, 'import $1 from $2;');
await mkdir(resolve(app, 'src/generated'), { recursive: true });
await writeFile(resolve(app, 'src/generated/theme-schemas.ts'), '// @ts-nocheck\n// Generated by scripts/generate-theme-schemas.mjs; do not edit.\n' + code);
